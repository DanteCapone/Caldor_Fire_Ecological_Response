required_file <- function(path) {
  if (!file.exists(path)) stop("Required source is missing: ", path)
  path
}

copy_output <- function(source, destination) {
  required_file(source)
  if (file.exists(destination) &&
      identical(unname(tools::md5sum(source)), unname(tools::md5sum(destination)))) {
    return(invisible(destination))
  }
  ok <- file.copy(source, destination, overwrite = TRUE, copy.date = TRUE)
  if (!ok) stop("Could not copy ", source, " to ", destination)
  invisible(destination)
}

slugify <- function(x) {
  x %>%
    str_to_lower() %>%
    str_replace_all("[^a-z0-9]+", "_") %>%
    str_replace_all("^_|_$", "")
}

add_outer_label <- function(image, label, label_height = 100, point_size = 54) {
  info <- image_info(image)
  canvas <- image_extent(
    image,
    geometry = sprintf("%dx%d", info$width, info$height + label_height),
    gravity = "south",
    color = "white"
  )
  image_annotate(
    canvas,
    label,
    gravity = "northwest",
    location = "+28+16",
    size = point_size,
    weight = 700,
    color = "black",
    font = "Times New Roman"
  )
}

combine_vertical <- function(sources, labels, destination) {
  if (length(sources) != length(labels)) stop("sources and labels must align")
  images <- map2(sources, labels, function(path, label) {
    add_outer_label(image_read(required_file(path)), label)
  })
  image_write(image_append(image_join(images), stack = TRUE), destination)
  invisible(destination)
}

label_single <- function(source, label, destination) {
  image_write(add_outer_label(image_read(required_file(source)), label), destination)
  invisible(destination)
}

