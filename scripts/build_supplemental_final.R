build_s10_page <- function(window_start, window_end, exclude_years, window_kind,
                          destination, page_label, tag_start) {
  available_spec <- variable_spec %>%
    filter(variable %in% s10_core_variables) %>%
    rowwise() %>%
    mutate(
      n_window = sum(
        drivers_native$variable == variable &
          drivers_native$date >= window_start &
          drivers_native$date <= window_end &
          is.finite(drivers_native$value)
      )
    ) %>%
    ungroup() %>%
    filter(n_window > 0)

  panels <- pmap(
    available_spec,
    function(variable, title, ylab, color, n_window) {
      make_driver_panel(
        variable, title, ylab, color,
        window_start, window_end, exclude_years, window_kind,
        show_x = FALSE
      )
    }
  )
  panels <- append(panels, list(
    make_chla_panel(
      window_start, window_end, exclude_years, window_kind,
      show_x = window_kind == "2011"
    ),
    make_lepto_panel(window_start, window_end, window_kind, TRUE)
  ))

  tag_theme <- theme(
    plot.tag = element_text(
      size = LO_FS_TAG, face = "bold", family = BASE_FAMILY,
      hjust = 1, vjust = 1
    ),
    plot.tag.position = c(.98, .98)
  )
  if (window_kind == "2011") {
    tag_theme <- tag_theme + theme(
      plot.caption = element_text(size = 8.5, family = BASE_FAMILY, hjust = 0.5,
                                  margin = margin(t = 1.5, unit = "mm"))
    )
  }

  figure <- wrap_plots(panels, ncol = 2, byrow = TRUE, guides = "collect") +
    plot_annotation(
      tag_levels = list(letters[tag_start + seq_along(panels) - 1L]),
      caption = if (window_kind == "2011") "2011-2012" else NULL
    )
  figure <- figure & tag_theme & theme(
    legend.position = "bottom",
    legend.direction = "horizontal",
    legend.justification = "center",
    legend.title = element_blank(),
    legend.text = element_text(size = LO_FONT_MIN_PT, family = BASE_FAMILY),
    legend.key.height = unit(1.8, "mm"),
    legend.key.width = unit(3, "mm"),
    legend.spacing.x = unit(1, "mm"),
    legend.margin = margin(0.5, 0.5, 0.5, 0.5, "mm")
  )

  ragg::agg_png(
    destination,
    width = LO_WIDTH_MAX,
    height = LO_HEIGHT_MAX,
    units = "cm",
    res = LO_DPI_LINE
  )
  print(figure)
  invisible(dev.off())
  ggsave(
    paste0(tools::file_path_sans_ext(destination), ".pdf"), figure,
    width = LO_WIDTH_MAX, height = LO_HEIGHT_MAX, units = "cm", device = cairo_pdf
  )

  inventory_variables <- c(
    available_spec$variable,
    "chlorophyll_a_by_depth",
    "leptolyngbya_abundance"
  )
  inventory_titles <- c(
    available_spec$title,
    "Chlorophyll a (0-40 m and 60-105 m)",
    "Leptolyngbya abundance (0-40 m and 60-105 m)"
  )
  tibble(
    page = page_label,
    variable = inventory_variables,
    title = inventory_titles,
    focal_years_excluded_from_climatology = paste(exclude_years, collapse = ";"),
    window_start = as.character(window_start),
    window_end = as.character(window_end)
  )
}

