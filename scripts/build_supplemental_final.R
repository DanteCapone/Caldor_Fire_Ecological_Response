      axis.text = element_text(size = LO_FONT_MIN_PT),
      axis.text.y = element_text(margin = margin(r = 1, unit = "pt")),
      plot.title = element_text(
        size = LO_FONT_MIN_PT, face = "plain", hjust = 0,
        margin = margin(b = 0.5, unit = "mm")
      ),
      plot.margin = margin(0.5, 0.8, 0.5, 0.8, "mm")
    )
  if (!show_x) {
    result <- result + theme(axis.text.x = element_blank(), axis.ticks.x = element_blank())
  }
  result
}

add_window_markers <- function(plot, window_kind) {
  if (window_kind == "2011") {
    plot
  } else {
    plot +
      annotate(
        "rect", xmin = CALDOR_START, xmax = CALDOR_END,
        ymin = -Inf, ymax = Inf, fill = "firebrick", alpha = 0.07
      )
  }
}

s10_date_labels <- function(x, window_kind) {
  labels <- format(x, "%b")
  if (window_kind != "2011" && length(x) > 0L) {
    first_year_tick <- !duplicated(year(x))
    labels[first_year_tick] <- paste0(
      labels[first_year_tick], "\n", year(x[first_year_tick])
    )
  }
  labels
}

climatology_for_window <- function(variable_id, window_start, window_end, exclude_years) {
  monthly_reference <- drivers_monthly %>%
    filter(variable == variable_id, !year %in% exclude_years) %>%
    group_by(month) %>%
    summarise(
      mean = mean(value, na.rm = TRUE),
      sd = sd(value, na.rm = TRUE),
      n = sum(is.finite(value)),
      .groups = "drop"
    ) %>%
    mutate(
      se = sd / sqrt(n),
      critical_t = if_else(n >= 2, qt(0.975, n - 1), NA_real_),
      lower = mean - critical_t * se,
      upper = mean + critical_t * se
    )

  tibble(date = seq(floor_date(window_start, "month"), floor_date(window_end, "month"), by = "month")) %>%
    mutate(month = month(date)) %>%
    left_join(monthly_reference, by = "month")
}

make_driver_panel <- function(variable_id, title, ylab, color, window_start,
                              window_end, exclude_years, window_kind, show_x) {
  observed <- drivers_native %>%
    filter(variable == variable_id, date >= window_start, date <= window_end, is.finite(value))
  if (nrow(observed) == 0) return(NULL)

  climatology <- climatology_for_window(variable_id, window_start, window_end, exclude_years)
  plot <- ggplot() %>% add_window_markers(window_kind)
  plot <- plot +
    geom_ribbon(
      data = climatology,
      aes(date, ymin = lower, ymax = upper),
      fill = "grey75", alpha = 0.45, na.rm = TRUE
    ) +
    geom_line(
      data = climatology,
      aes(date, mean),
      color = "grey35", linetype = "dashed", linewidth = LO_LW_THIN,
      na.rm = TRUE
    ) +
    geom_line(
      data = observed,
      aes(date, value),
      color = color, linewidth = LO_LW_MID, alpha = 0.9, na.rm = TRUE
    )
  if (variable_id %in% c("din_srp_deposition_molar", "din_srp_inlake_molar")) {
    plot <- plot + geom_hline(yintercept = 16, linetype = "dotted", color = "black")
  }
  if (variable_id %in% c(
    "par_1pct_depth_m", "mixed_layer_depth_m", "secchi_depth_m"
  )) {
    plot <- plot + scale_y_reverse()
  }
  plot +
    scale_x_date(
      limits = c(window_start, window_end),
      date_breaks = "2 months",
      labels = function(x) s10_date_labels(x, window_kind),
      expand = expansion(mult = 0.01)
    ) +
    labs(
      x = NULL, y = ylab,
      title = if (variable_id %in% c("mixed_layer_depth_m", "secchi_depth_m")) {
        title
      } else {
        NULL
      }
    ) +
    panel_theme(show_x)
}

make_chla_panel <- function(window_start, window_end, exclude_years,
                            window_kind, show_x) {
  observed <- chla_zone_native %>%
    filter(
      date >= floor_date(window_start, "month"),
      date <= floor_date(window_end, "month")
    )

  variable_depth_map <- c(
    "chla_0_40_ugl" = "0-40 m",
    "chla_60_105_ugl" = "60-105 m"
  )
  climatology <- imap_dfr(variable_depth_map, function(depth_zone, variable_id) {
    climatology_for_window(
      variable_id, window_start, window_end, exclude_years
    ) %>%
      mutate(depth_zone = depth_zone)
  })

  plot <- ggplot() %>% add_window_markers(window_kind)
  plot +
    geom_ribbon(
      data = climatology,
      aes(date, ymin = lower, ymax = upper, fill = depth_zone),
      alpha = 0.12, colour = NA, na.rm = TRUE
    ) +
    geom_line(
      data = climatology,
      aes(date, mean, colour = depth_zone, group = depth_zone),
      linetype = "dashed", linewidth = LO_LW_THIN, alpha = 0.75,
      na.rm = TRUE
    ) +
    geom_line(
      data = observed,
      aes(date, value, colour = depth_zone, group = depth_zone),
      linewidth = LO_LW_MID, alpha = 0.95, na.rm = TRUE
    ) +
    scale_colour_manual(values = LEPTO_DEPTH_COLS, guide = "none") +
    scale_fill_manual(values = LEPTO_DEPTH_COLS, guide = "none") +
    scale_x_date(
      limits = c(window_start, window_end),
      date_breaks = "2 months",
      labels = function(x) s10_date_labels(x, window_kind),
      expand = expansion(mult = 0.01)
    ) +
    labs(
      x = NULL,
      y = expression(mu * "g L"^-1),
      title = "Chlorophyll a"
    ) +
    panel_theme(show_x) +
    theme(legend.position = "none")
}

